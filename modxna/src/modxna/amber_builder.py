def run_minimization(output_dir: Path) -> bool:
    """Run 2-stage minimization using sander to fix structural clashes.

    As noted in the LiveCoMS tutorial: LEaP creates a linearized structure
    with overlaps. Running minimization produces a clash-free structure.

    Stages:
        1. min1: Restrained minimization (solvent only, solute fixed)
        2. min2: Full system minimization

    Args:
        output_dir: Output directory containing aso.parm7, aso.crd, md_inputs/

    Returns:
        True if successful, outputs aso.min.rst7 and aso.min.pdb
    """
    md_inputs = output_dir / "md_inputs"
    prmtop = output_dir / "aso.parm7"
    inpcrd = output_dir / "aso.crd"

    # Check required files exist
    if not prmtop.exists():
        print(f"Error: topology not found: {prmtop}")
        return False
    if not inpcrd.exists():
        print(f"Error: coordinates not found: {inpcrd}")
        return False
    if not (md_inputs / "min1.in").exists():
        print(f"Error: min1.in not found in {md_inputs}")
        return False

    try:
        # Stage 1: Restrained minimization (solvent only)
        print("  Running min1 (restrained)...")
        result = subprocess.run(
            [
                "sander", "-O",
                "-i", str(md_inputs / "min1.in"),
                "-o", str(output_dir / "min1.out"),
                "-p", str(prmtop),
                "-c", str(inpcrd),
                "-r", str(output_dir / "min1.rst7"),
                "-ref", str(inpcrd),
            ],
            capture_output=True,
            text=True,
            check=False,
            env=_get_env(),
        )

        if result.returncode != 0:
            print(f"min1 failed with return code {result.returncode}")
            print(f"stderr: {result.stderr}")
            return False

        # Stage 2: Full system minimization
        print("  Running min2 (full system)...")
        result = subprocess.run(
            [
                "sander", "-O",
                "-i", str(md_inputs / "min2.in"),
                "-o", str(output_dir / "min2.out"),
                "-p", str(prmtop),
                "-c", str(output_dir / "min1.rst7"),
                "-r", str(output_dir / "aso.min.rst7"),
            ],
            capture_output=True,
            text=True,
            check=False,
            env=_get_env(),
        )

        if result.returncode != 0:
            print(f"min2 failed with return code {result.returncode}")
            print(f"stderr: {result.stderr}")
            return False

        # Convert minimized structure to PDB using cpptraj
        print("  Converting to PDB...")
        cpptraj_script = f"""\
parm {prmtop}
trajin {output_dir}/aso.min.rst7
trajout {output_dir}/aso.min.pdb pdb
run
quit
"""
        result = subprocess.run(
            ["cpptraj"],
            input=cpptraj_script,
            capture_output=True,
            text=True,
            check=False,
            env=_get_env(),
        )

        if result.returncode != 0:
            print(f"cpptraj failed with return code {result.returncode}")
            print(f"stderr: {result.stderr}")
            return False

        # Verify output
        min_pdb = output_dir / "aso.min.pdb"
        if not min_pdb.exists():
            print("Error: aso.min.pdb was not created")
            return False

        print(f"  Minimized structure: {min_pdb}")
        return True

    except FileNotFoundError as e:
        print(f"Error: required program not found: {e}")
        print("Make sure AmberTools (sander, cpptraj) is installed and in PATH.")
        return False
    except Exception as e:
        print(f"Error during minimization: {e}")
        return False
